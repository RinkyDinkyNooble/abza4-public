// Item tooltips: the tier an item can be crafted in, in that tier's colour; a note for some items; and, in
// dark grey, an earlier tier it can be found in
const TIER_COLOURS = {"1": 10212186, "2": 7329512, "3": 14725184, "4": 13158600, "5": 14708778, "6": 5223306, "7": 9417945, "8": 11022918}

function tierLines(entry) {
    const lines = []
    if (entry[0]) lines.push(Text.of(`Tier ${entry[0]}`).color(TIER_COLOURS[entry[0]]))
    if (entry[2]) lines.push(Text.gray(entry[2]))
    if (entry[1]) lines.push(Text.darkGray(`Can be found as early as Tier ${entry[1]}`))
    return lines
}

